"""Export the post-V3 ladder's bytes, for the Rust port to match.

WHY THIS EXISTS
===============
Between the V3 registration response and `InGame` the client walks a fixed ladder. Two rungs are
composed messages whose shape came from another emulator (first-light) and was validated live here.
The third is a **captured** message, and that distinction is the point of this script.

WHAT IS COMPOSED AND WHAT IS CAPTURED
=====================================
    composed   Cmd_Greetings                     GridMate's stock peer handshake
    composed   PlayerManagerSelfIdentification   first-light RE, validated live
    CAPTURED   LevelInfoChanged (wire 0x663)     replay seqs 0x10 and 0x4d

The prototype also has a `level_info_changed_body()` function. **It is dead code, never called, and
its layout does not match the capture**: it composes 92 bytes where the real message is 106, and the
second string is a `coatlicue/`-prefixed path rather than the plain level name. Anyone porting from
it would send a malformed message. So LIC is exported from the capture, not composed.

The remaining rungs — the spawn record and the ongoing state stream — are captured payloads with
their own fixtures (`player-record-1.bin`).

Usage:
    python scripts/export-ladder-fixtures.py
"""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "server" / "crates" / "azoth-wire" / "tests" / "fixtures" / "ladder.json"


def load_blocks():
    """Reuse the corpus reader rather than re-implement its hexdump handling."""
    spec = importlib.util.spec_from_file_location(
        "mig", REPO / "scripts" / "measure-inventory-grammar.py"
    )
    mig = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mig)
    return mig.load_blocks(REPO / "services" / "world" / "replay" / "messages-redacted.txt")


def main() -> int:
    blocks = load_blocks()
    first = blocks["0x10_T0x663_R.bin"]
    second = blocks["0x4d_T0x663_R.bin"]
    if first != second:
        print("FAIL: the two captured LIC copies differ, so neither is a safe fixture")
        return 1
    # `00 01` typed marker, then a two-byte prefix varint (0x663), then the body.
    body = first[4:]

    fixtures = {
        "$comment": (
            "The post-V3 ladder's bytes. `source` says for each whether it was composed or taken "
            "from the capture — the distinction matters, because one composed *prototype* function "
            "turned out to be dead code with a wrong layout. Generated by "
            "scripts/export-ladder-fixtures.py; do not hand-edit."
        ),
        "build_sha256": "30fe6461f929ba44178376a72f0765dc5da28ccba20e5006a60a229babd74033",
        "greetings": {
            "source": "composed (GridMate Cmd_Greetings, stock protocol)",
            "payload_hex": (
                bytes([1]) + (0x415A4F54).to_bytes(4, "big") + bytes([1])
                + (1 << 25).to_bytes(4, "big")
            ).hex(),
        },
        "self_identification": {
            "source": "composed (first-light RE, validated live here)",
            "wire_type": 0x5D1,
            "body_hex": (
                (0).to_bytes(4, "little") * 2 + b"\x00"
                + (0).to_bytes(8, "little") + (0).to_bytes(4, "little")
            ).hex(),
        },
        "level_info_changed": {
            "source": "CAPTURED — replay seqs 0x10 and 0x4d, byte-identical",
            "wire_type": 0x663,
            "body_hex": body.hex(),
            "body_len": len(body),
            "decoded": {
                "level": "NewWorld_VitaeEterna",
                "level_prefix": "coatlicue/NewWorld_VitaeEterna",
                "four_f32_be": [2048.0, 16.0, 12272.0, 10250.0],
                "tail_bytes_unexplained": 38,
            },
            "note": (
                "The prototype's level_info_changed_body composes 92 bytes and is never called; the "
                "real message is 106. This fixture is the real one."
            ),
        },
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(fixtures, indent=1) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")
    print(f"  greetings   {len(fixtures['greetings']['payload_hex']) // 2} B payload")
    print(f"  self-ident  {len(fixtures['self_identification']['body_hex']) // 2} B body")
    print(f"  LIC 0x663   {len(body)} B body (captured)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
