"""Generate the channel-document parity fixture from the Python gateway.

WHY THIS EXISTS
===============
The Rust renderer must produce the same document the Python gateway produces, for the same
registry. Without a fixture that claim is untested, and the channel document is the one response
every client fetches before it can do anything (187 requests to `/STEAM_APP_ID.json`).

The fixture is self-contained: it carries the registry as JSON the Rust types deserialize, plus the
exact bytes the Python gateway renders for it. A fresh checkout can therefore run the parity test
with no gateway, no client and no capture.

WHAT IT READS
-------------
`services/gateway/src/azoth_gateway/data/channel-azoth.json` (the document the prototype serves,
whose region entries are overridden at render time by the registry) and `worlds.json` (the registry
the prototype reads).

The output is NOT the prototype's file copied: the region block is rebuilt from `worlds.json` the
same way `routes/channel.py` does it, so the fixture records the *rendering contract* rather than a
snapshot of a file that happens to be right today.

Usage:
    python scripts/export-channel-fixture.py
"""

from __future__ import annotations

import json
import sys
from copy import deepcopy
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
DATA = REPO / "services" / "gateway" / "src" / "azoth_gateway" / "data"
OUT = REPO / "server" / "crates" / "azoth-region" / "tests" / "fixtures" / "channel-parity.json"

sys.path.insert(0, str(REPO / "services" / "gateway" / "src"))
from azoth_gateway.util.etag import etag_for  # noqa: E402


def render_python() -> tuple[bytes, str]:
    """Reproduce `routes/channel.py::channel_response` exactly."""
    base = json.loads((DATA / "channel-azoth.json").read_text(encoding="utf-8"))
    worlds = json.loads((DATA / "worlds.json").read_text(encoding="utf-8"))
    doc = deepcopy(base)
    for region in worlds.get("regions", []):
        entry = doc.get(region.get("id"))
        if entry is not None:
            entry["displayName"] = region.get("displayName", "")
            entry["localizedName"] = region.get("displayName", "")
    body = (json.dumps(doc, indent=2) + "\n").encode()
    return body, etag_for(body)


def main() -> int:
    worlds = json.loads((DATA / "worlds.json").read_text(encoding="utf-8"))
    base = json.loads((DATA / "channel-azoth.json").read_text(encoding="utf-8"))
    body, etag = render_python()

    # Rebuild the registry in the Rust types' snake_case shape, from the same two files.
    regions = []
    for region in worlds.get("regions", []):
        rid = region.get("id")
        entry = base.get(rid) or {}
        regions.append({
            "id": rid,
            "display_name": region.get("displayName", ""),
            # routes/channel.py sets localizedName to the display name, overriding the file.
            "localized_name": region.get("displayName", ""),
            "pool_id": entry.get("poolId", ""),
            "public_apis": [
                {
                    "client_tag": api.get("clientTag", ""),
                    "api_endpoint": api.get("apiEndpoint", ""),
                    "aws_region": api.get("awsRegion"),
                    "version": api.get("version"),
                    "stage": api.get("stage"),
                }
                for api in entry.get("publicApis", [])
            ],
            "status": "ACTIVE",
            # The region's own dotted privacy keys, which the base file carries inside the region.
            "privacy_settings": {
                key: value
                for key, value in entry.items()
                if key.startswith("omni.privacy-settings.") and isinstance(value, str)
            },
        })

    # The configuration blocks: everything in the base document that is not a region.
    region_keys = {r["id"] for r in regions}
    platform_metadata = base.get("platformMetadata", {})
    omni = base.get("omni", {})
    top_level_privacy = [
        (key, value)
        for key, value in base.items()
        if key.startswith("omni.privacy-settings.") and isinstance(value, str)
    ]

    fixture = {
        "$comment": (
            "Channel-document parity fixture. `expected_body` is what the Python gateway renders "
            "for `registry` + `config`; the Rust test must produce the same bytes. Generated by "
            "scripts/export-channel-fixture.py."
        ),
        "build_sha256": "30fe6461f929ba44178376a72f0765dc5da28ccba20e5006a60a229babd74033",
        "config": {
            "channel_name": base.get("channelName", ""),
            "platform_metadata": platform_metadata,
            "omni": omni,
            "top_level_privacy": top_level_privacy,
        },
        "registry": {"regions": regions, "worlds": []},
        "expected_etag": etag,
        "expected_body": body.decode(),
        "notes": [
            f"base document keys: {sorted(base)}",
            f"region keys in the registry: {sorted(region_keys)}",
        ],
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(fixture, indent=1) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")
    print(f"  regions: {len(regions)}")
    print(f"  expected body: {len(body)} bytes")
    print(f"  expected etag: {etag}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
