#!/usr/bin/env python3
"""Generate the wire-boundary fixture the Rust protocol crate is tested against.

WHY THIS EXISTS. `docs/ROADMAP.md` section 4 names one piece of this project as
genuinely port-ready: the wire codecs (`varint`, the type-0x08 state bundle), which
have round-trip tests against the captured corpus in Python. The rule for the port is
"compare Rust and Python at the wire boundary using the same fixtures and observed
client results", so the port needs a fixture generated FROM the Python implementation
and read by the Rust tests — not a second hand-written expectation that can drift.

FORMAT. A line-oriented text file, not JSON, so the Rust side needs no dependency at
all (the repository's standard-library preference applies to the port too):

    varint <value> <hex> <size>
    bundle <seq> <replication_seq> <payload_len> <first_record_id> <first_record_fragments>
    <body hex, one line>
    frag <key> <type_index> <payload_len>
    <fragment payload hex, one line>
    boundary <offset>

CONTENT. Every captured bundle below 2 KB (for shape variety), the four 7154-byte
record-1 bundles the state stream sends, and ONE 46393-byte spawn record (the only
body that carries the player's position). The record-1 fragment boundaries are
included because they are protocol data derived from the client's own readers and the
Rust side must not recompute them.

Usage:
  python scripts/gen-protocol-fixture.py            # write the fixture
  python scripts/gen-protocol-fixture.py --check    # fail if it would change
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "services" / "world" / "src"))

from azoth_world.javelin import bundle as javelin_bundle  # noqa: E402
from azoth_world.javelin import varint  # noqa: E402
from azoth_world.javelin.replay_store import ReplayStore  # noqa: E402

OUT = ROOT / "server" / "crates" / "protocol" / "tests" / "fixtures" / "state-bundles.txt"
STORE = ROOT / "services" / "world" / "replay" / "messages-redacted.txt"

# The record-1 (local-player metadata) fragment boundaries, DERIVED FROM THE CLIENT
# (reverse/probes/client/frida-fragment-grammar.py). A fragment carries no length field,
# so these cannot be recomputed from bytes.
PLAYER_BOUNDARIES = [2, 60, 3955, 4295, 4301, 4498, 5335, 5386, 7125]
PLAYER_SOURCE_SEQS = (0x98, 0x9A, 0x9C, 0x9E)
SPAWN_SEQ = 0x2A
SMALL_LIMIT = 2048

# Varint cases: every width boundary, plus the type ids and lengths that were
# hand-verified against the capture (see javelin/varint.py's docstring).
VARINT_VALUES = [
    0, 1, 0x7E, 0x7F, 0x80, 0xBF, 0xC0, 0x1FFF, 0x2000, 0x3FFF,
    349, 1635, 5792, 7048, 692, 46393, 4216, 2334,
    (1 << 21) - 1, 1 << 21, (1 << 28) - 1, 1 << 28, varint.MAX_VALUE,
]


def build() -> str:
    store = ReplayStore(STORE)
    bundles = [m for m in store.messages if m.type_id == 0x08 and m.direction == "R"]

    lines: list[str] = []
    lines.append("# Generated by scripts/gen-protocol-fixture.py. Do not edit by hand.")
    lines.append("# The Python codecs are the reference; the Rust crate must match them.")
    lines.append("")
    lines.append("# varint <value> <hex> <size>")
    for v in VARINT_VALUES:
        lines.append(f"varint {v} {varint.encode(v).hex()} {varint.size_of(v)}")

    count = 0
    for m in bundles:
        if m.seq == 0x25:
            # The first message of its datagram carries a datagram-level preamble, so its
            # body does not start with the typed marker (documented in bundle.py).
            continue
        if not (len(m.body) <= SMALL_LIMIT or m.seq in PLAYER_SOURCE_SEQS or m.seq == SPAWN_SEQ):
            continue
        parsed = javelin_bundle.decode_bundle(m.body)
        first_id = parsed.payload[0] if parsed.payload else -1
        first_frags = parsed.payload[1] if len(parsed.payload) > 1 else -1
        lines.append("")
        lines.append(
            f"bundle 0x{m.seq:x} {parsed.replication_seq} {len(parsed.payload)} "
            f"{first_id} {first_frags}"
        )
        lines.append(m.body.hex())
        count += 1

    player_body = next(m.body for m in bundles if m.seq == PLAYER_SOURCE_SEQS[0])
    player_payload = javelin_bundle.decode_bundle(player_body).payload
    fragments = [
        javelin_bundle.parse_fragment(raw)
        for raw in javelin_bundle.split_record_payload(player_payload, PLAYER_BOUNDARIES)
    ]
    lines.append("")
    lines.append("# record-1 (local-player metadata) fragment layout, derived from the client")
    for off in PLAYER_BOUNDARIES:
        lines.append(f"boundary {off}")
    for f in fragments:
        lines.append(f"frag {f.key} {f.type_index} {len(f.payload)}")
        lines.append(f.payload.hex())
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    text = build()
    if args.check:
        if not OUT.is_file():
            print(f"missing {OUT}")
            return 1
        if OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is out of date; re-run without --check")
            return 1
        print(f"fixture OK ({OUT.stat().st_size} bytes)")
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
